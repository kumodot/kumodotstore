"""Writes the lookup tables the order decoder needs (colors, firmware badges, knob models) as JSON, read from the
store's own source files, so the packing list never drifts from the Kustomizer.

usage: python tools/export_order_tables.py
Writes docs/order-tables.json and copies it to LOCAL_STORE_MANAGER/app/fm1_tables.json. Run it after you add a
color or a firmware in the Studio (and publish)."""
import json, os, re, shutil

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
MANAGER = r"D:/Google_Drive_Bkp/DIY/DIY_POCASEs/STORE_TOOLS/LOCAL_STORE_MANAGER/app"

colors_src = open(os.path.join(ROOT, "src/data/colors.ts"), encoding="utf-8").read()
colors = []
for m in re.finditer(r'\{ id: "([^"]+)", name: "([^"]+)", rgb: \[[^\]]+\], hex: "(#[0-9a-fA-F]{6})", available: (true|false)([^}]*)\}', colors_src):
    extra = m.group(5)
    colors.append({"id": m.group(1), "name": m.group(2), "hex": m.group(3).lower(), "translucent": "translucent: true" in extra})

fw_src = open(os.path.join(ROOT, "src/data/firmwares.ts"), encoding="utf-8").read()
firmwares = []
for m in re.finditer(r'\{ id: "([^"]+)", code: "([^"]+)", name: "([^"]+)", logo: (null|"[^"]*"), bezel: "([^"]+)"', fw_src):
    firmwares.append({"id": m.group(1), "code": m.group(2), "name": m.group(3), "has_logo": m.group(4) != "null", "bezel": m.group(5)})

tables = {
    "_about": "Generated by tools/export_order_tables.py from src/data/colors.ts and src/data/firmwares.ts. Do not edit by hand.",
    "colors": colors,
    "firmwares": firmwares,
    "knob_models": {"CS": "Classic Short", "CL": "Chalice", "GS": "Groove Short", "GL": "Groove Long"},
    "slots": {"L": ["VOL", "SEL.", "PRESET", "ALG."], "R": ["K1", "K2", "K3", "K4"]},
}
os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
out = os.path.join(ROOT, "docs/order-tables.json")
json.dump(tables, open(out, "w", encoding="utf-8"), indent=2)
print(f"{len(colors)} colors, {len(firmwares)} firmwares ->", os.path.normpath(out))
if os.path.isdir(MANAGER):
    shutil.copy(out, os.path.join(MANAGER, "fm1_tables.json"))
    print("copied to", MANAGER + "/fm1_tables.json")
